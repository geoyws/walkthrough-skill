// ---------------------------------------------------------------- utilities

function die(message, code = 1) {
  process.stderr.write(`walkthrough: ${message}\n`);
  process.exit(code);
}

function read(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

function writeFile(file, body) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body);
}

function writeIfAbsent(file, body) {
  if (fs.existsSync(file)) return false;
  writeFile(file, body);
  return true;
}

function fill(template, values) {
  return template.replace(/\{\{([A-Z_]+)\}\}/g, (whole, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : whole,
  );
}

function q(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function readJson(file) {
  const raw = read(file);
  if (raw === null) return null;
  try {
    return JSON.parse(raw);
  } catch (error) {
    die(`cannot parse ${file}: ${error.message}`);
  }
  return null;
}

function git(args, cwd) {
  return execFileSync('git', args, {
    cwd,
    encoding: 'utf8',
    maxBuffer: 1 << 28,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

function gitTry(args, cwd) {
  try {
    return git(args, cwd);
  } catch {
    return null;
  }
}

function table(header, rows) {
  const out = [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`];
  for (const row of rows) out.push(`| ${row.map((c) => String(c ?? '')).join(' | ')} |`);
  return out.join('\n');
}

function cell(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

// ---------------------------------------------------------------- repo model

function inferRepo() {
  const here = path.dirname(fileURLToPath(import.meta.url));
  if (path.basename(here) === 'bin' && path.basename(path.dirname(here)) === 'walkthrough') {
    return path.resolve(here, '../../..');
  }
  return process.cwd();
}

function parseArgs(argv) {
  const out = { command: null, repo: null, base: null, reset: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--repo') out.repo = argv[++i];
    else if (arg === '--base') out.base = argv[++i];
    else if (arg === '--reset-site') out.reset = true;
    else if (arg === '-h' || arg === '--help') out.command = 'help';
    else if (!out.command) out.command = arg;
  }
  return out;
}

function normaliseBase(base) {
  let value = String(base || '/').trim();
  if (!value.startsWith('/')) value = `/${value}`;
  if (!value.endsWith('/')) value = `${value}/`;
  return value.replace(/\/{2,}/g, '/');
}

function defaultConfig(repo) {
  const workspaces = [];
  for (const dir of ['apps', 'packages', 'services']) {
    if (fs.existsSync(path.join(repo, dir))) workspaces.push(`${dir}/*`);
  }
  const areas = [];
  for (const pattern of workspaces) {
    for (const pkgDir of expandWorkspace(repo, pattern)) {
      const slug = pkgDir.split('/').pop();
      areas.push({ slug, name: slug, kind: pattern.startsWith('apps') ? 'app' : 'package', path: pkgDir });
    }
  }
  for (const sub of listSubmodules(repo)) {
    if (areas.some((a) => a.path === sub.path)) continue;
    areas.push({ slug: sub.path.split('/').pop(), name: sub.path, kind: 'submodule', path: sub.path });
  }
  if (fs.existsSync(path.join(repo, 'scripts'))) {
    areas.push({ slug: 'tooling', name: 'Root tooling', kind: 'tooling', path: 'scripts' });
  }
  return {
    title: path.basename(repo),
    description: 'Codebase walkthrough.',
    base: '/',
    adrDir: 'docs/adr',
    workspaces,
    areas,
  };
}

function loadConfig(repo) {
  const file = path.join(repo, SITE, 'walkthrough.config.json');
  const parsed = readJson(file);
  if (!parsed) die(`missing ${SITE}/walkthrough.config.json — run \`init\` first`);
  const config = {
    title: parsed.title || path.basename(repo),
    description: parsed.description || '',
    base: normaliseBase(parsed.base || '/'),
    adrDir: parsed.adrDir || 'docs/adr',
    workspaces: Array.isArray(parsed.workspaces) ? parsed.workspaces : [],
    areas: Array.isArray(parsed.areas) ? parsed.areas : [],
  };
  for (const area of config.areas) {
    if (!area.slug || !area.path) die(`config area missing slug or path: ${JSON.stringify(area)}`);
    area.kind = area.kind || 'package';
    area.name = area.name || area.slug;
  }
  return config;
}

// Only simple `dir/*` globs, per contract.
function expandWorkspace(repo, pattern) {
  const found = [];
  if (!pattern.endsWith('/*')) {
    if (fs.existsSync(path.join(repo, pattern, 'package.json'))) found.push(pattern);
    return found;
  }
  const dir = pattern.slice(0, -2);
  let entries = [];
  try {
    entries = fs.readdirSync(path.join(repo, dir), { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory() || entry.name.startsWith('.')) continue;
    const rel = `${dir}/${entry.name}`;
    if (fs.existsSync(path.join(repo, rel, 'package.json'))) found.push(rel);
  }
  return found;
}

function workspacePackages(repo, config) {
  const dirs = [];
  for (const pattern of config.workspaces) {
    for (const rel of expandWorkspace(repo, pattern)) if (!dirs.includes(rel)) dirs.push(rel);
  }
  return dirs.map((rel) => ({ rel, pkg: readJson(path.join(repo, rel, 'package.json')) || {} }));
}

function gitmodulesAt(repo, levelRel) {
  const file = path.join(repo, levelRel, '.gitmodules');
  if (!fs.existsSync(file)) return [];
  const raw = gitTry(['config', '-f', file, '--get-regexp', '^submodule\\.'], repo);
  if (!raw) return [];
  const byName = new Map();
  for (const line of raw.split('\n')) {
    const match = /^submodule\.(.+)\.(path|url|branch)\s+(.*)$/.exec(line.trim());
    if (!match) continue;
    const [, name, key, value] = match;
    if (!byName.has(name)) byName.set(name, { name });
    byName.get(name)[key] = value;
  }
  return [...byName.values()];
}

function listSubmodules(repo) {
  const raw = gitTry(['submodule', 'status', '--recursive'], repo);
  if (!raw) return [];
  const states = { ' ': 'ok', '-': 'not-initialised', '+': 'sha-differs', 'U': 'conflict' };
  const entries = [];
  for (const line of raw.split('\n')) {
    if (!line.trim()) continue;
    const flag = line[0] === ' ' ? ' ' : line[0];
    const rest = (line[0] === ' ' ? line.slice(1) : line.slice(1)).trim();
    const match = /^([0-9a-f]{40})\s+(\S+)(?:\s+\((.*)\))?$/.exec(rest);
    if (!match) continue;
    entries.push({
      path: match[2],
      sha: match[1],
      describe: match[3] || '',
      state: states[flag] || 'unknown',
    });
  }
  entries.sort((a, b) => a.path.localeCompare(b.path));
  const paths = entries.map((e) => e.path);
  return entries.map((entry) => {
    const parents = paths.filter((p) => p !== entry.path && entry.path.startsWith(`${p}/`));
    parents.sort((a, b) => b.length - a.length);
    const level = parents[0] || '';
    const within = level ? entry.path.slice(level.length + 1) : entry.path;
    const declared = gitmodulesAt(repo, level).find((m) => m.path === within) || {};
    return {
      path: entry.path,
      sha: entry.sha,
      url: declared.url || '',
      branch: declared.branch || '',
      depth: parents.length + 1,
      state: entry.state,
    };
  });
}

function rootState(repo) {
  const sha = gitTry(['rev-parse', 'HEAD'], repo);
  if (!sha) die('not a git repository (or no commits yet)');
  const branch = (gitTry(['rev-parse', '--abbrev-ref', 'HEAD'], repo) || '').trim();
  const dirty = (gitTry(['status', '--porcelain'], repo) || '').trim().length > 0;
  const full = sha.trim();
  return { sha: full, short: full.slice(0, 10), branch: branch || 'HEAD', dirty };
}

function stamp() {
  const tz =
    process.env.WALKTHROUGH_TZ ||
    process.env.TZ ||
    Intl.DateTimeFormat().resolvedOptions().timeZone ||
    'UTC';
  const now = new Date();
  const utc = `${now.toISOString().slice(0, 19)}Z`;
  let local = utc;
  try {
    const parts = new Intl.DateTimeFormat('en-CA', {
      timeZone: tz,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
      timeZoneName: 'short',
    }).formatToParts(now);
    const get = (type) => (parts.find((p) => p.type === type) || {}).value || '';
    local = `${get('year')}-${get('month')}-${get('day')} ${get('hour')}:${get('minute')} ${get('timeZoneName')}`;
  } catch {
    local = utc;
  }
  return { utc, local, tz };
}

// ---------------------------------------------------------------- generated

function pageInventory(repo, config) {
  const rows = config.areas.map((area) => {
    const abs = path.join(repo, area.path);
    const pkg = readJson(path.join(abs, 'package.json')) || {};
    const scripts = Object.keys(pkg.scripts || {});
    return [
      area.name,
      `\`${area.path}\``,
      area.kind,
      pkg.name ? `\`${pkg.name}\`` : '—',
      cell(pkg.description || (fs.existsSync(abs) ? '' : 'path missing in this checkout')),
      scripts.length ? scripts.slice(0, 8).join(', ') + (scripts.length > 8 ? ', …' : '') : '—',
    ];
  });
  return [
    GENERATED_NOTE,
    '# Inventory',
    '',
    `${config.areas.length} configured area(s).`,
    '',
    table(['Area', 'Path', 'Kind', 'Package', 'Description', 'Scripts'], rows),
    '',
  ].join('\n');
}

function pageSubmodules(subs) {
  const body = subs.length
    ? table(
        ['Path', 'Depth', 'Pinned', 'Branch', 'URL', 'Checkout'],
        subs.map((s) => [
          `\`${s.path}\``,
          s.depth,
          `\`${s.sha.slice(0, 10)}\``,
          s.branch || '—',
          s.url ? `\`${cell(s.url)}\`` : '—',
          s.state,
        ]),
      )
    : 'No gitlinks in this repository.';
  return [GENERATED_NOTE, '# Submodules', '', `${subs.length} gitlink(s), all depths.`, '', body, ''].join('\n');
}

function pageScripts(repo, config) {
  const lines = [GENERATED_NOTE, '# Scripts', ''];
  const root = readJson(path.join(repo, 'package.json')) || {};
  const rootScripts = Object.entries(root.scripts || {});
  lines.push(`## Root (\`package.json\`)`, '');
  lines.push(
    rootScripts.length
      ? table(['Script', 'Command'], rootScripts.map(([k, v]) => [`\`${k}\``, `\`${cell(v)}\``]))
      : 'No root scripts.',
  );
  lines.push('');
  for (const { rel, pkg } of workspacePackages(repo, config)) {
    const entries = Object.entries(pkg.scripts || {});
    lines.push(`## ${pkg.name || rel}`, '', `Path: \`${rel}\``, '');
    lines.push(
      entries.length
        ? table(['Script', 'Command'], entries.map(([k, v]) => [`\`${k}\``, `\`${cell(v)}\``]))
        : 'No scripts.',
    );
    lines.push('');
  }
  return lines.join('\n');
}

function adrFiles(repo, config) {
  const dir = path.join(repo, config.adrDir);
  let names = [];
  try {
    names = fs.readdirSync(dir).filter((n) => n.endsWith('.md'));
  } catch {
    return [];
  }
  return names.sort().map((name) => {
    const body = read(path.join(dir, name)) || '';
    const heading = /^#\s+(.+)$/m.exec(body);
    const status = /^\s*(?:[-*]\s*)?(?:\*\*)?status(?:\*\*)?\s*[::]\s*(.+)$/im.exec(body);
    const number = (/^(\d+)/.exec(name) || [, ''])[1];
    return {
      file: `${config.adrDir}/${name}`,
      number,
      title: heading ? heading[1].trim() : name.replace(/\.md$/, ''),
      status: status ? status[1].trim() : '',
    };
  });
}

function pageAdrs(repo, config) {
  const adrs = adrFiles(repo, config);
  const body = adrs.length
    ? table(
        ['#', 'Title', 'Status', 'File'],
        adrs.map((a) => [a.number || '—', cell(a.title), cell(a.status) || '—', `\`${a.file}\``]),
      )
    : `No ADR files under \`${config.adrDir}\`.`;
  return [GENERATED_NOTE, '# ADRs', '', `${adrs.length} record(s) in \`${config.adrDir}\`.`, '', body, ''].join('\n');
}

function logFor(repo, range, pathspec) {
  const raw = gitTry(['log', '--no-merges', '--format=%h %s', range, '--', ...pathspec], repo);
  if (raw === null) return null;
  return raw.split('\n').filter((l) => l.trim());
}

function hasCommit(repo, sha, cwd) {
  return gitTry(['cat-file', '-e', `${sha}^{commit}`], cwd || repo) !== null;
}

function pageChanges(repo, config, previous, subs) {
  const lines = [GENERATED_NOTE, '# Changes since last refresh', ''];
  const prev = previous && previous.rootSha;
  if (!prev) {
    const now = rootState(repo);
    lines.push(`First refresh at ${now.short}; no baseline.`, '');
    return lines.join('\n');
  }
  if (!hasCommit(repo, prev)) {
    lines.push(`Previous root commit ${prev.slice(0, 10)} is not in the local store; no diff possible.`, '');
    return lines.join('\n');
  }
  const range = `${prev}..HEAD`;
  lines.push(`Range: \`${prev.slice(0, 10)}..HEAD\``, '');
  const covered = [];
  for (const area of config.areas) {
    covered.push(area.path);
    lines.push(`## ${area.name}`, '', `Path: \`${area.path}\``, '');
    const log = logFor(repo, range, [area.path]) || [];
    const stat = (gitTry(['diff', '--shortstat', range, '--', area.path], repo) || '').trim();
    lines.push(`${log.length} commit(s).${stat ? ` ${stat}` : ''}`, '');
    for (const entry of log.slice(0, 30)) lines.push(`- ${entry}`);
    if (log.length > 30) lines.push(`- … ${log.length - 30} more`);
    lines.push('');
  }
  lines.push('## Other (outside every configured area)', '');
  const exclude = covered.map((p) => `:(exclude)${p}`);
  const otherLog = logFor(repo, range, ['.', ...exclude]) || [];
  lines.push(`${otherLog.length} commit(s).`, '');
  for (const entry of otherLog.slice(0, 30)) lines.push(`- ${entry}`);
  if (otherLog.length > 30) lines.push(`- … ${otherLog.length - 30} more`);
  lines.push('');

  lines.push('## Submodule moves', '');
  const before = new Map((previous.submodules || []).map((s) => [s.path, s.sha]));
  let moved = 0;
  for (const sub of subs) {
    const was = before.get(sub.path);
    if (!was || was === sub.sha) continue;
    moved += 1;
    lines.push(`### \`${sub.path}\``, '', `\`${was.slice(0, 10)}\` -> \`${sub.sha.slice(0, 10)}\``, '');
    const cwd = path.join(repo, sub.path);
    if (!fs.existsSync(cwd)) {
      lines.push('Submodule is not checked out here; no log available.', '');
      continue;
    }
    if (!hasCommit(repo, was, cwd)) {
      lines.push('Baseline commit not in local store.', '');
      continue;
    }
    const log = (gitTry(['-C', cwd, 'log', '--no-merges', '--format=%h %s', `${was}..${sub.sha}`], repo) || '')
      .split('\n')
      .filter((l) => l.trim());
    lines.push(`${log.length} commit(s).`, '');
    for (const entry of log.slice(0, 30)) lines.push(`- ${entry}`);
    if (log.length > 30) lines.push(`- … ${log.length - 30} more`);
    lines.push('');
  }
  if (!moved) lines.push('No submodule pins moved.', '');

  lines.push('## ADR files added or removed', '');
  const names = (gitTry(['diff', '--name-status', range, '--', config.adrDir], repo) || '')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .filter((l) => /^[AD]\t/.test(l));
  if (!names.length) lines.push('None.', '');
  else {
    for (const line of names) {
      const [flag, file] = line.split('\t');
      lines.push(`- ${flag === 'A' ? 'added' : 'removed'} \`${file}\``);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function authoredPages(repo) {
  const siteAbs = path.join(repo, SITE);
  const out = [];
  const walk = (dir) => {
    let entries = [];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      const abs = path.join(dir, entry.name);
      const rel = path.relative(siteAbs, abs).split(path.sep).join('/');
      if (entry.isDirectory()) {
        if (['generated', 'node_modules', '.vitepress', 'bin'].includes(entry.name)) continue;
        walk(abs);
      } else if (entry.name.endsWith('.md') && !rel.startsWith('generated/')) {
        out.push({ rel, abs });
      }
    }
  };
  walk(siteAbs);
  return out;
}

const PATH_TOKEN = /^[A-Za-z0-9_.-]+(\/[A-Za-z0-9_.@-]+)+$/;

export function citationMisses(repo, body) {
  const misses = [];
  const seen = new Set();
  for (const match of body.matchAll(/`([^`\n]+)`/g)) {
    const token = match[1].trim();
    if (!token || /\s/.test(token) || !token.includes('/')) continue;
    if (token.startsWith('~') || token.startsWith('/') || token.includes('://')) continue;
    if (token.includes('node_modules')) continue;
    const bare = token.replace(/:\d+(-\d+)?$/, '').replace(/\/$/, '');
    if (!PATH_TOKEN.test(bare)) continue;
    if (seen.has(bare)) continue;
    seen.add(bare);
    if (!fs.existsSync(path.join(repo, bare))) misses.push(bare);
  }
  return misses;
}

function pageDrift(repo) {
  const lines = [GENERATED_NOTE, '# Drift', '', 'Cited repo paths on authored pages that do not resolve.', ''];
  let total = 0;
  for (const page of authoredPages(repo)) {
    const misses = citationMisses(repo, read(page.abs) || '');
    if (!misses.length) continue;
    total += misses.length;
    lines.push(`## \`${SITE}/${page.rel}\``, '');
    for (const miss of misses) lines.push(`- \`${miss}\` does not exist`);
    lines.push('');
  }
  if (!total) lines.push('Clean: every cited path resolves.', '');
  return { body: lines.join('\n'), total };
}

