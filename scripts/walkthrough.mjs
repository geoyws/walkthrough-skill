function sidebarSource(config) {
  const areas = config.areas.length
    ? config.areas.map((a) => `      { text: ${q(a.name)}, link: '/areas/${a.slug}' },`).join('\n')
    : '';
  const generated = [
    ['Inventory', 'inventory'],
    ['Submodules', 'submodules'],
    ['Scripts', 'scripts'],
    ['ADRs', 'adrs'],
    ['Changes', 'changes'],
    ['Drift', 'drift'],
  ]
    .map(([text, slug]) => `      { text: '${text}', link: '/generated/${slug}' },`)
    .join('\n');
  return [
    'const sidebar = [',
    '  {',
    "    text: 'Guide',",
    '    items: [',
    "      { text: 'Overview', link: '/' },",
    "      { text: 'Reading order', link: '/guide/reading-order' },",
    "      { text: 'Traps', link: '/guide/traps' },",
    "      { text: 'Glossary', link: '/guide/glossary' },",
    '    ],',
    '  },',
    '  {',
    "    text: 'Areas',",
    '    items: [',
    areas,
    '    ],',
    '  },',
    '  {',
    "    text: 'Generated',",
    '    items: [',
    generated,
    '    ],',
    '  },',
    ']',
  ]
    .filter((line) => line !== '')
    .join('\n');
}

function rewriteSidebar(configFile, config) {
  const body = read(configFile);
  if (body === null) return false;
  const begin = body.indexOf(SIDEBAR_BEGIN);
  const end = body.indexOf(SIDEBAR_END);
  if (begin === -1 || end === -1 || end < begin) return false;
  const head = body.slice(0, begin + SIDEBAR_BEGIN.length);
  const tail = body.slice(end);
  fs.writeFileSync(configFile, `${head}\n${sidebarSource(config)}\n${tail}`);
  return true;
}

// ---------------------------------------------------------------- commands

function manifestFile(repo) {
  return path.join(repo, SITE, 'manifest.json');
}

function cmdRefresh(repo) {
  const config = loadConfig(repo);
  const root = rootState(repo);
  const subs = listSubmodules(repo);
  const old = readJson(manifestFile(repo));
  const previous = old
    ? {
        rootSha: old.root ? old.root.sha : null,
        refreshedAtUtc: old.refreshedAt ? old.refreshedAt.utc : null,
        submodules: old.submodules || [],
      }
    : null;

  const changes = pageChanges(repo, config, previous, subs);
  const drift = pageDrift(repo);
  const site = path.join(repo, SITE);
  writeFile(path.join(site, 'generated/inventory.md'), pageInventory(repo, config));
  writeFile(path.join(site, 'generated/submodules.md'), pageSubmodules(subs));
  writeFile(path.join(site, 'generated/scripts.md'), pageScripts(repo, config));
  writeFile(path.join(site, 'generated/adrs.md'), pageAdrs(repo, config));
  writeFile(path.join(site, 'generated/changes.md'), changes);
  writeFile(path.join(site, 'generated/drift.md'), drift.body);

  const manifest = {
    generator: { ...GENERATOR },
    refreshedAt: stamp(),
    root,
    submodules: subs.map((s) => ({
      path: s.path,
      sha: s.sha,
      url: s.url,
      branch: s.branch,
      depth: s.depth,
    })),
    previous: {
      rootSha: previous ? previous.rootSha : null,
      refreshedAtUtc: previous ? previous.refreshedAtUtc : null,
    },
  };
  writeFile(manifestFile(repo), `${JSON.stringify(manifest, null, 2)}\n`);

  const configFile = path.join(site, '.vitepress/config.mts');
  const rewrote = rewriteSidebar(configFile, config);

  process.stdout.write(
    [
      `refreshed ${config.title} at ${root.short} on ${root.branch}${root.dirty ? ' (dirty)' : ''}`,
      `areas: ${config.areas.length}  submodules: ${subs.length}  adrs: ${adrFiles(repo, config).length}`,
      `sidebar: ${rewrote ? 'rewritten' : 'markers not found, left alone'}`,
      `drift: ${drift.total === 0 ? 'clean' : `${drift.total} unresolved citation(s)`}`,
    ].join('\n') + '\n',
  );
  if (drift.total) process.stdout.write(`${drift.body.split('\n').slice(4).join('\n').trim()}\n`);
  return 0;
}

function cmdCheck(repo) {
  const manifest = readJson(manifestFile(repo));
  if (!manifest) {
    process.stdout.write('STALE . none -> unknown\n');
    return 1;
  }
  const root = rootState(repo);
  const lines = [];
  if (!manifest.root || manifest.root.sha !== root.sha) {
    const was = manifest.root ? manifest.root.short : 'none';
    lines.push(`STALE . ${was} -> ${root.short}`);
  }
  const live = new Map(listSubmodules(repo).map((s) => [s.path, s.sha]));
  for (const sub of manifest.submodules || []) {
    const now = live.get(sub.path);
    if (now === undefined) lines.push(`STALE ${sub.path} ${sub.sha.slice(0, 10)} -> absent`);
    else if (now !== sub.sha) lines.push(`STALE ${sub.path} ${sub.sha.slice(0, 10)} -> ${now.slice(0, 10)}`);
  }
  const known = new Set((manifest.submodules || []).map((s) => s.path));
  for (const [p, sha] of live) {
    if (!known.has(p)) lines.push(`STALE ${p} absent -> ${sha.slice(0, 10)}`);
  }
  if (lines.length) {
    process.stdout.write(`${lines.join('\n')}\n`);
    return 1;
  }
  process.stdout.write(`FRESH ${manifest.root.short}\n`);
  return 0;
}

function patchPackageJson(repo) {
  const file = path.join(repo, 'package.json');
  const pkg = readJson(file) || { name: path.basename(repo), private: true, version: '0.0.0' };
  pkg.scripts = pkg.scripts || {};
  const added = [];
  for (const [key, value] of Object.entries(SCRIPTS)) {
    if (!(key in pkg.scripts)) {
      pkg.scripts[key] = value;
      added.push(key);
    }
  }
  pkg.devDependencies = pkg.devDependencies || {};
  if (!('vitepress' in pkg.devDependencies)) {
    pkg.devDependencies.vitepress = VITEPRESS_VERSION;
    added.push('devDependencies.vitepress');
  }
  fs.writeFileSync(file, `${JSON.stringify(pkg, null, 2)}\n`);
  return added;
}

function cmdInit(repo, args) {
  const site = path.join(repo, SITE);
  const created = [];
  const configFile = path.join(site, 'walkthrough.config.json');
  if (!fs.existsSync(configFile)) {
    writeFile(configFile, `${JSON.stringify(defaultConfig(repo), null, 2)}\n`);
    created.push(`${SITE}/walkthrough.config.json`);
  }
  const config = loadConfig(repo);

  const self = fileURLToPath(import.meta.url);
  const vendored = path.join(site, 'bin/walkthrough.mjs');
  if (path.resolve(self) !== path.resolve(vendored)) {
    fs.mkdirSync(path.dirname(vendored), { recursive: true });
    fs.copyFileSync(self, vendored);
    fs.chmodSync(vendored, 0o755);
    created.push(`${SITE}/bin/walkthrough.mjs`);
  }

  const siteConfig = path.join(site, '.vitepress/config.mts');
  if (!fs.existsSync(siteConfig) || args.reset) {
    writeFile(
      siteConfig,
      fill(TPL_CONFIG_MTS, {
        SIDEBAR: sidebarSource(config),
        TITLE: config.title.replace(/'/g, "\\'"),
        DESCRIPTION: (config.description || '').replace(/'/g, "\\'"),
        BASE: config.base,
        AREAS_LINK: config.areas.length ? `/areas/${config.areas[0].slug}` : '/generated/inventory',
      }),
    );
    created.push(`${SITE}/.vitepress/config.mts`);
  }
  if (writeIfAbsent(path.join(site, '.vitepress/theme/index.ts'), TPL_THEME_INDEX)) {
    created.push(`${SITE}/.vitepress/theme/index.ts`);
  }
  if (writeIfAbsent(path.join(site, '.vitepress/theme/Layout.vue'), TPL_LAYOUT_VUE)) {
    created.push(`${SITE}/.vitepress/theme/Layout.vue`);
  }

  const pages = [
    ['index.md', fill(TPL_PAGE_INDEX, { TITLE: config.title, DESCRIPTION: config.description })],
    ['guide/reading-order.md', TPL_PAGE_READING_ORDER],
    ['guide/traps.md', TPL_PAGE_TRAPS],
    ['guide/glossary.md', TPL_PAGE_GLOSSARY],
  ];
  for (const area of config.areas) {
    pages.push([
      `areas/${area.slug}.md`,
      fill(TPL_PAGE_AREA, { AREA_NAME: area.name, AREA_KIND: area.kind, AREA_PATH: area.path }),
    ]);
  }
  for (const [rel, body] of pages) {
    if (writeIfAbsent(path.join(site, rel), body)) created.push(`${SITE}/${rel}`);
  }

  const added = patchPackageJson(repo);
  process.stdout.write(
    [
      created.length ? `created:\n${created.map((c) => `  ${c}`).join('\n')}` : 'created: nothing (all present)',
      added.length ? `package.json: added ${added.join(', ')}` : 'package.json: already wired',
      added.includes('devDependencies.vitepress')
        ? 'next: install dependencies so that node_modules/.bin/vitepress exists'
        : '',
    ]
      .filter(Boolean)
      .join('\n') + '\n',
  );
  return cmdRefresh(repo);
}

function vitepressBin(repo) {
  const bin = path.join(repo, 'node_modules/.bin/vitepress');
  if (!fs.existsSync(bin)) {
    process.stderr.write(
      `walkthrough: ${path.relative(repo, bin)} not found — install devDependencies (e.g. \`pnpm install\`) in ${repo}\n`,
    );
    process.exit(1);
  }
  return bin;
}

function resolveBase(repo, args) {
  if (args.base) return normaliseBase(args.base);
  if (process.env.WALKTHROUGH_BASE) return normaliseBase(process.env.WALKTHROUGH_BASE);
  return loadConfig(repo).base;
}

function runVitepress(repo, argv) {
  const result = spawnSync(vitepressBin(repo), argv, { cwd: repo, stdio: 'inherit' });
  return result.status === null ? 1 : result.status;
}

function cmdBuild(repo, args) {
  const base = resolveBase(repo, args);
  cmdCheck(repo);
  const status = runVitepress(repo, ['build', SITE, '--base', base]);
  if (status !== 0) return status;
  // Publish the stamp beside the pages: a host that serves this dist answers
  // `<base>manifest.json`, which is how a deploy proves WHICH commit is live
  // without scraping the footer.
  const dist = path.join(repo, SITE, '.vitepress/dist');
  fs.copyFileSync(path.join(repo, SITE, 'manifest.json'), path.join(dist, 'manifest.json'));
  return 0;
}

// `localhost` rather than the loopback literal: same binding, and this file
// lives in a public repository whose privacy gate rejects bare IP addresses.
const DEV_HOST = 'localhost';

function cmdDev(repo, args) {
  return runVitepress(repo, ['dev', SITE, '--host', DEV_HOST, '--port', '5180', '--base', resolveBase(repo, args)]);
}

function cmdServe(repo, args) {
  return runVitepress(repo, [
    'preview',
    SITE,
    '--host',
    DEV_HOST,
    '--port',
    '5181',
    '--base',
    resolveBase(repo, args),
  ]);
}

const USAGE = `walkthrough-skill ${GENERATOR.version} — generate a codebase walkthrough site

usage: node walkthrough.mjs <command> [--repo DIR] [--base PATH]

commands:
  init      scaffold docs/walkthrough/, vendor this script, wire package.json, refresh
  refresh   regenerate generated/*, manifest.json and the config sidebar region
  check     compare the stamp against HEAD and every submodule; exit 1 when stale
  build     vitepress build docs/walkthrough (base: --base > WALKTHROUGH_BASE > config)
  dev       vitepress dev on localhost:5180
  serve     vitepress preview on localhost:5181

flags:
  --repo DIR      target repository root (default: inferred from this script's location)
  --base PATH     site base path for build/dev/serve
  --reset-site    let init overwrite .vitepress/config.mts

env:
  WALKTHROUGH_BASE   base path fallback
  WALKTHROUGH_TZ     timezone used for the local stamp
`;

export function main(argv) {
  const args = parseArgs(argv);
  if (!args.command || args.command === 'help') {
    process.stdout.write(USAGE);
    return 2;
  }
  const repo = path.resolve(args.repo || inferRepo());
  if (!fs.existsSync(repo)) die(`no such directory: ${repo}`);
  switch (args.command) {
    case 'init':
      return cmdInit(repo, args);
    case 'refresh':
      return cmdRefresh(repo);
    case 'check':
      return cmdCheck(repo);
    case 'build':
      return cmdBuild(repo, args);
    case 'dev':
      return cmdDev(repo, args);
    case 'serve':
      return cmdServe(repo, args);
    default:
      process.stderr.write(`walkthrough: unknown command '${args.command}'\n\n${USAGE}`);
      return 2;
  }
}

// Node resolves the main module through symlinks, so import.meta.url is the
// realpath while process.argv[1] is whatever the caller typed (for example a
// ~/.agents/skills/walkthrough symlink). Compare realpaths or a symlinked
// invocation silently does nothing.
const invokedDirectly = (() => {
  if (!process.argv[1]) return false;
  try {
    return fs.realpathSync(fileURLToPath(import.meta.url)) === fs.realpathSync(process.argv[1]);
  } catch {
    return false;
  }
})();
if (invokedDirectly) process.exit(main(process.argv.slice(2)));
